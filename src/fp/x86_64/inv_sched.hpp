// qv_chain[n][u] for n = 20..316 fraction digits (beta = 2^52; k = 18..256 limbs),
// u = 1 when the last level may be unguarded (sh = 52 n - T >= 4): bits 0..3 = L, the number of levels; then one 4-bit
// code per level from the top, level t (t = n first) coming from h = t / 2 + code (code 0: the unguarded h = t / 2,
