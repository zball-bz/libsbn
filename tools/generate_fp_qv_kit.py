#!/usr/bin/env python3
"""Generate src/fp/x86_64/qv_kit.S: the IFMA level sections shared by the fp reciprocal's engine (inv_engine.S,
tools/generate_fp_inv_engine.py) and the fp reciprocal square root's engine (rsqrt_engine.S, tools/generate_fp_rsqrt_engine.py).
  usage: generate_fp_qv_kit.py [--check] [OUT.S]; writes OUT (default src/fp/x86_64/qv_kit.S); --check generates in memory and
  compares with OUT (exit status 1 if they differ).

Both engine generators emit these sections with the same text (tools/fp_qv/kit.py has the list); with --kit-emit each prints
only them. This script runs both, requires the two outputs to be equal and writes that text under the header below, so the
kit is by construction the code each engine had in its own object before (MULSHARE T1, fp_mulshare_2026-10-17)."""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
argv = sys.argv[1:]
CHECK = '--check' in argv
argv = [x for x in argv if x != '--check']
out = Path(argv[0]) if argv else ROOT / 'src/fp/x86_64/qv_kit.S'
gen = lambda g: subprocess.run([sys.executable, '-B', str(ROOT / 'tools' / g), '--kit-emit'], check=True, capture_output=True,
                               text=True).stdout
inv, rs = gen('generate_fp_inv_engine.py'), gen('generate_fp_rsqrt_engine.py')
if inv != rs:
    raise SystemExit('the engines\' shared sections differ: generate_fp_inv_engine.py --kit-emit != generate_fp_rsqrt_engine.py --kit-emit')
PAD = 23                                # the sections start at byte 23 of a 64-byte line (int3 before): the segment loops'
assert inv.count('.text\n.p2align 6\n') == 1   # placement in the rsqrt engine they come from (the loops are not aligned)
inv = inv.replace('.text\n.p2align 6\n', f'.text\n.p2align 6\n.skip {PAD}, 0xcc\n')
hdr = ('/* Generated by tools/generate_fp_qv_kit.py; do not edit. The IFMA level sections shared by the fp engines\n'
       ' * sbn3f_inv_chain (inv_engine.S) and sbn3f_rsqrt_chain / sbn3f_rsqrt_chain_cu (rsqrt_engine.S): the text both engine\n'
       ' * generators emit for them (--kit-emit, checked equal), one copy (MULSHARE T1). Internal entries, hidden: sbn3f_qvk_<name>.\n'
       ' *   z<v>      Z: the MP\'s start of vectors v .. 0 (group 0\'s lo = the init row at r11 - 8 + 64 v, the other groups zero)\n'
       ' *   seg<s>    SEG: the staircase of segment loops s .. 0 (U = 4 rows per iteration over vectors 0 .. s; r10 x down,\n'
       ' *             r11 y up, ecx iterations, eax segments still to run, r9d segment 0\'s iterations), then sx: the group\n'
       ' *             sums; seg<s>_r<r>: the entry at row r of segment s\'s first iteration (the engines\' Duff tables)\n'
       ' *   rcp<v>    the reduction of vector v, then rc<v>; rc<v>: RC, the reductions of vectors v - 1 .. 0 and the fast canon\n'
       ' *             round of vectors v .. 0 (lanes left above M52 or-ed into zmm5)\n'
       ' *   gz<v>     GZ: G = V xor M52 of vectors v .. 0 (lanes below e zeroed by k1 / k2) stored at rdx + 64 v, accumulators zeroed\n'
       ' *   upd<v>    UPD: X[r13 + 64 v] += C of vectors v .. 0 (k1 / k2 lanes, -2 at k3 / k4), the sums or-ed into zmm7\n'
       ' *   exact     (cold) vectors 0..9 stored at F + r8 (F = the caller\'s rsp; r8 = 0 or 640), the exact carry pass over\n'
       ' *             F[0 .. NV) (r14d = NV), vectors 0..9 reloaded from F + r8; canon_mem: the pass over rdi[0 .. esi)\n'
       ' * Registers: the row groups of vectors 0..9 in zmm0..zmm29 (lo zmm0..14, hi zmm15..29; 4, 2, 2, 1, .. groups; V_v / H_v =\n'
       ' * group 0), zmm30 / zmm31 the row X / T and PHI / CPHI, temporaries zmm1..zmm3 (vector 0\'s lo groups 1..3, free after the\n'
       ' * group sums); exact also rax, rcx, rsi, rdi, k5..k7 (canon_mem keeps r10, r11). The sections are entered by call from\n'
       ' * inside an engine\'s frame and return by ret. The tables of these entries (.Ldtab, .Lbig_tab) are in each engine.\n'
       ' */\n')
if CHECK:
    if not out.exists() or out.read_text() != hdr + inv:
        raise SystemExit(f'{out} differs from tools/generate_fp_qv_kit.py\'s output')
    print(f'OK: {out} is tools/generate_fp_qv_kit.py\'s output')
else:
    out.write_text(hdr + inv)
