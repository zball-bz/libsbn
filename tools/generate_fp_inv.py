def spec_step(m, n, F, tag, ending):
    """X_n from X_m: F = X_m's fraction limbs in registers (also stored at XT - 8m ..), the leading one implicit; all in
    registers. MP into Acc; G = ~Acc[2 ..] stays in registers; the correction rows run over X_m's limbs (reloaded from
    memory) with G's limbs as the second operand, into fresh accumulators. ending: 'rt' (BIAS slot: 0 = mid: -2, clamp,
    store; else + bias, then the final pack from registers when K = n, else store). Optional cubic term (CUBF slot, n = 2m:
    G through memory). Returns X_n's registers (the leading limb in rbx)."""
    w = n - m
    W = w + 3
    Acc = [r for r in POOL if r not in F][:W]
    assert len(Acc) == W
    coarse = (m, n) == (4, 8)                          # quadratic: the carry columns are noise against Delta_4^2
    def mp(t0, lbl):
        for q in range(t0, W):
            e(f'\tmovq\t{D(q - 1, n)}, %{Acc[q]}')
        for j in range(m):
            e(f'\tmovq\t%{F[j]}, %rdx')
            e('\txorl\t%eax, %eax')
            for t in range(t0, W):
                i = m - 1 - j + t
                if i > n:
                    e(f'\tadcq\t$0, %{Acc[t]}')
                    continue
                e(f'\tmulxq\t{D(i, n)}, %rax, %rbx')
                e(f'\tadcxq\t%rax, %{Acc[t]}')
                if t + 1 < W:
                    e(f'\tadoxq\t%rbx, %{Acc[t + 1]}')
        if lbl:
            e(f'\tjmp\t{lbl}')
    if coarse:
        # without the lower carry column (column m-1; the upper one carries the hi halves into G's lowest limb) G is
        # in [E / B^(m+1) - 1, E / B^(m+1) + m + 1) (model), C high by < 2(m + 1) = 10: the base subtracts 12, the
        # final's bias is centred on [-4917, +10]; the cubic route (k = 8, ld >= 55) keeps the full window
        e(f'\tcmpq\t$0, {CUBF}(%rsp)')
        e(f'\tjne\t.Lc_full_{tag}')
        mp(1, f'.Lc_mpd_{tag}')
        e(f'.Lc_full_{tag}:')
        mp(0, None)
        e(f'.Lc_mpd_{tag}:')
    else:
        mp(0, None)
    G = Acc[2:W]                                       # w + 1 limbs
    Gregs[tag] = G
    for r in G:
        e(f'\tnotq\t%{r}')
    keepF = 2 * w + 7 + m <= 15                        # X_m's limbs stay in registers (else reloaded)
    if tag == 's26':
        # FIX s26: G' = G + floor(Gt^2 / B^2), Gt = G's top 3 limbs = G / B^2 (n = 3m: G^2 / B^6 = Gt^2 / B^2 + [0, 14.0005))
        tmp = [r for r in POOL + ['rax', 'rbx'] if r not in G and (not keepF or r not in F)]
        e(f'.Lc_hsq_{tag}:')
        S2, S3, S4, S5 = sq3(G[w - 2:w + 1], tmp[:7])
        e(f'\taddq\t%{S2}, %{G[0]}')
        e(f'\tadcq\t%{S3}, %{G[1]}')
        e(f'\tadcq\t%{S4}, %{G[2]}')
        e(f'\tadcq\t%{S5}, %{G[3]}')
