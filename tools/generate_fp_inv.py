    e(f'\tadcq\t%{h}, %{t3}')
    e(f'\tmovq\t%{a[2]}, %rdx')
    e(f'\tmulxq\t%rdx, %{l}, %{h}')                  # a2^2: columns 4, 5
    e(f'\tadcq\t%{l}, %{t4}')
