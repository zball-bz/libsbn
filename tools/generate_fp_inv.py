def spec_cold(m, n, tag, Fregs):
    """the cold paths of spec_step: the clamp (X_n < B^n after -2: X_n = B^n) and the cubic term"""
    w = n - m
    X = None
    e(f'.Lc_clamp_{tag}:')
    # X_n = B^n: zero the registers holding X_n's limbs is done by the caller's register list; here via memory: the
    # store follows the clamp, so zero the registers named in Fregs (X_n's limbs)
    for r in Fregs:
        e(f'\txorl\t%{r32(r)}, %{r32(r)}')
    e('\tmovl\t$1, %ebx')
    e(f'\tjmp\t.Lc_clampd_{tag}')
