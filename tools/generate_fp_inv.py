def sq3(a, T):
    """exact Gt^2 for Gt = a[0] + a[1] B + a[2] B^2 in registers: returns the registers of columns 2..5 (columns 0, 1
    are formed and carried, then dropped); T: 7 temporaries (not rdx, not a). 6 mulx, 24 instructions"""
    t1, t2, t3, t4, t5, l, h = T
    e(f'\tmovq\t%{a[0]}, %rdx')
    e(f'\tmulxq\t%{a[1]}, %{t1}, %{t2}')             # a0 a1: columns 1, 2
    e(f'\tmulxq\t%{a[2]}, %{l}, %{t3}')              # a0 a2: columns 2, 3
    e(f'\tmulxq\t%rdx, %{t5}, %{h}')                 # a0^2: column 1 (h); column 0 dropped
    e(f'\taddq\t%{l}, %{t2}')
    e(f'\tadcq\t$0, %{t3}')
    e(f'\tmovq\t%{a[1]}, %rdx')
    e(f'\tmulxq\t%{a[2]}, %{l}, %{t4}')              # a1 a2: columns 3, 4
    e(f'\taddq\t%{l}, %{t3}')
    e(f'\tadcq\t$0, %{t4}')
    e(f'\txorl\t%{r32(t5)}, %{r32(t5)}')
    e(f'\taddq\t%{t1}, %{t1}')                        # the cross triangle doubled (columns 1..5)
    e(f'\tadcq\t%{t2}, %{t2}')
    e(f'\tadcq\t%{t3}, %{t3}')
    e(f'\tadcq\t%{t4}, %{t4}')
