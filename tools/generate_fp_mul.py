#!/usr/bin/env python3
"""Generate src/fp/x86_64/mul.S: the fp kernel mul / sqr entries (contract: src/fp/kernel.hpp).

  fxr sbn3f_mul(limb *z, const fx *a, const fx *b, int64_t leps)   rdi z, rsi a, rdx b, rcx leps
  fxr sbn3f_sqr(limb *z, const fx *a, int64_t leps)                rdi z, rsi a, rdx leps
  result: rax e, rdx ns

k = ea + eb - floor((leps - 2) / 64) output limbs (kernel.hpp's mul_shape). k <= 0: zero. Both
operands at least k limbs: the high product of their top k limbs (a pointer offset each), error
< 4 units of 2^(64(ea + eb - k)): two truncations < 1 each, the high product < 2. Otherwise the full
product of the windows min(n, k) (exact for the windows; < 1 unit). The top limb of a high product
of normalized windows is zero at most once (the kept sum holds the top limbs' product), except a
zero result; the strip loop takes any count.

Entry: 2(n - k) = 2n - 2k by one subtraction per operand (its borrow is the shape test, its value
the window offset), then one indirect jump through an absolute table indexed by k (1..KTAB: the
per-k bodies, then the u52 path).

High products, the kept terms of tools/generate_high_half.py (every product a_i b_j with
i + j >= k - 1, the high limb of those with i + j = k - 2; the same terms for squares):
  k <= KRM (products) / KRQ (squares): generate_high_half.py's register columns (mul_regs,
    sqr_regs: columns k-1 .. 2k-1 in registers, MULX + ADOX + ADCX per product), with this file's
    red-zone layout: ns -8, e_top -16, callee-saved -24 .., b -72, z -80 (products beyond 8, squares
    of 11).
  then to KM (products) / KQ (squares): generate_high_half.py's rows with memory columns.
  beyond: the u52 kernels (the integer layer's sbn3i_mulhigh_u52), 40k + 256 bytes of scratch on the
    stack below an rbp frame.
Full products: sbn3f_full (the integer layer's scalar / u52 choice, scratch on the stack).
The leaf paths keep e_top and ns in the red zone; the call paths in a 24-byte frame.
"""
import argparse
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import generate_high_half as hh  # noqa: E402
OUT = ROOT / 'src/fp/x86_64/mul.S'
KRM, KRQ, KM, KQ, KTAB = 10, 11, 14, 20, 234
X1_INLINE = 16                 # one-limb windows: the leaf mul_1 loop to this length, the integer mul_1 beyond
ZERO = '.Lfz(%rip)'


def mul_body(k):
    if k == 1:
        return ['    movq    (%rcx), %rdx', '    mulxq   (%rsi), %rax, %r8', '    movq    %r8, (%rdi)'], '%r8', []
    if k <= KRM:
        return hh.mul_regs(k, ZERO, -24, 'S_B', 'S_Z')
    e = hh.Emit(False)
    hh.mulhigh_rows(e, k)                                               # top limb in r8
    return e.lines, '%r8', []


def sqr_body(k):
    if k == 1:
        return ['    movq    (%rsi), %rdx', '    mulxq   %rdx, %rax, %r9', '    movq    %r9, (%rdi)'], '%r9', []
    if k <= KRQ:
        return hh.sqr_regs(k, ZERO, -24, 'S_Z')
    e = hh.Emit(False)
    hh.sqrhigh_rows(e, k)                                               # top limb in r9
    return e.lines, '%r9', []


def block(L, label, body):
    lines, top, restore = body
    L += ['    .p2align 4', f'{label}:'] + lines
    L += [f'    testq   {top}, {top}'] + restore
    L += ['    movq    S_ETOP, %rax', '    movq    S_NS, %rdx', '    jz      .Lstrip', '    ret']


def text():
    L = ['/* Generated by tools/generate_fp_mul.py; do not edit. fp kernel mul / sqr, x86-64 (BMI2, ADX).',
         ' * See the generator for the paths; the contract is src/fp/kernel.hpp\'s. */',
         '#ifndef FPK_PFX', '#define FPK_PFX sbn3f_', '#endif',
         '#define FPK_CAT2(a, b) a##b', '#define FPK_CAT(a, b) FPK_CAT2(a, b)', '#define SYM(x) FPK_CAT(FPK_PFX, x)',
         '#define S_NS -8(%rsp)', '#define S_ETOP -16(%rsp)', '#define S_B -72(%rsp)', '#define S_Z -80(%rsp)', '',
         '    .section .rodata', '    .p2align 3', '.Lfz:', '    .quad   0', '',
         '    .text', '    .p2align 5', '    .globl SYM(mul)', '    .type SYM(mul), @function', 'SYM(mul):',
         '    movq    16(%rsi), %r10', '    movq    16(%rdx), %r11',     # a.ns, b.ns
         '    movq    8(%rsi), %rax', '    addq    8(%rdx), %rax',      # e_top = ea + eb
         '    subq    $2, %rcx', '    sarq    $6, %rcx',               # L(2)
         '    movq    %rax, %r9', '    subq    %rcx, %r9',              # k
         '    jle     .Lzero',
         '    movq    %r10, %r8', '    xorq    %r11, %r8',              # sign in bit 63
         '    addq    %r10, %r10', '    addq    %r11, %r11',            # 2 na, 2 nb
         '    leaq    (%r9,%r9), %rcx',                                    # 2 k
         '    subq    %rcx, %r10', '    jb      .Lm_fa',                 # 2 (na - k)
         '    subq    %rcx, %r11', '    jb      .Lm_fb',
         '    shrq    $63, %r8', '    shlq    $63, %r8', '    addq    %r9, %r8',
         '    movq    (%rsi), %rsi', '    leaq    (%rsi,%r10,4), %rsi',   # the top k limbs
         '    movq    (%rdx), %rcx', '    leaq    (%rcx,%r11,4), %rcx',
         '    movq    %rax, S_ETOP', '    movq    %r8, S_NS',
         '    leaq    .Lm_tab(%rip), %rdx', '    jmp     *-8(%rdx,%r9,8)']
    for k in range(1, KM + 1):
        block(L, f'.Lm_{k}', mul_body(k))
    L += ['.Lm_u52:                                    # rsi, rcx windows, r9 = k; e_top, ns in the red zone',
          '    movq    %rcx, %rdx',
          '.Lu52:                                      # rsi a, rdx b, r9 k: the u52 high half, scratch on the stack',
          '    movq    S_NS, %r10', '    movq    S_ETOP, %r11',
          '    pushq   %rbp', '    movq    %rsp, %rbp',
          '    pushq   %rdi', '    pushq   %r11', '    pushq   %r10',
          '    imulq   $40, %r9, %rax', '    addq    $256, %rax',       # >= mulhigh_u52_bytes(k)
          '    subq    %rax, %rsp', '    andq    $-64, %rsp',
          '    movq    %rsp, %r8', '    movq    %r9, %rcx', '    call    sbn3i_mulhigh_u52',
          '    movq    -8(%rbp), %rdi', '    movq    -16(%rbp), %rax', '    movq    -24(%rbp), %rdx',
          '    leave',
          '    jmp     .Ltop',
          '.Lm_fb:', '    addq    %rcx, %r11',
          '.Lm_fa:', '    addq    %rcx, %r10',
          '                                            # rax e_top, r8 sign, r10 / r11 2n, rcx 2k',
          '    movq    (%rsi), %rsi', '    movq    (%rdx), %r9', '    movq    %rcx, %rdx',
          '    cmpq    %r10, %rdx', '    cmovaq  %r10, %rdx',            # 2 ka
          '    cmpq    %r11, %rcx', '    cmovaq  %r11, %rcx',            # 2 kb
          '    subq    %rdx, %r10', '    leaq    (%rsi,%r10,4), %rsi',
          '    subq    %rcx, %r11', '    leaq    (%r9,%r11,4), %r9',
          '    shrq    $1, %rdx', '    shrq    $1, %rcx',
          '    shrq    $63, %r8', '    shlq    $63, %r8', '    addq    %rdx, %r8', '    addq    %rcx, %r8',
          '    cmpq    $1, %rcx', '    je      .Lm_x1b',
          '    cmpq    $1, %rdx', '    je      .Lm_x1a',
          '    subq    $24, %rsp', '    movq    %rdi, (%rsp)', '    movq    %rax, 8(%rsp)', '    movq    %r8, 16(%rsp)',
          '    movq    %rcx, %r8', '    movq    %r9, %rcx', '    call    sbn3f_full',
          '    jmp     .Lafter',
          '.Lm_x1a:                                    # one limb times a window: z[0..p] = x * w, leaf',
          '    movq    %r9, %r10', '    movq    %rcx, %r11', '    movq    (%rsi), %rdx', '    jmp     .Lm_x1',
          '.Lm_x1b:',
          '    movq    %rsi, %r10', '    movq    %rdx, %r11', '    movq    (%r9), %rdx',
          '.Lm_x1:                                     # rdx x, r10 w, r11 p >= 1, rax e_top, r8 ns',
          f'    cmpq    ${X1_INLINE}, %r11', '    ja      .Lm_x1call',
          '    movq    %rax, S_ETOP', '    movq    %r8, S_NS',
          '    leaq    (%r10,%r11,8), %r10', '    leaq    (%rdi,%r11,8), %rsi', '    negq    %r11',
          '    xorl    %ecx, %ecx',
          '1:  mulxq   (%r10,%r11,8), %r9, %r8', '    adcxq   %rcx, %r9', '    movq    %r9, (%rsi,%r11,8)',
          '    movq    %r8, %rcx', '    incq    %r11', '    jnz     1b',
          '    movl    $0, %r9d', '    adcxq   %r9, %rcx', '    movq    %rcx, (%rsi)',
          '    testq   %rcx, %rcx', '    movq    S_ETOP, %rax', '    movq    S_NS, %rdx', '    jz      .Lstrip', '    ret',
          '.Lm_x1call:                                 # longer windows: the integer mul_1, carry -> z[p]',
          '    subq    $24, %rsp', '    movq    %rdi, (%rsp)', '    movq    %rax, 8(%rsp)', '    movq    %r8, 16(%rsp)',
          '    movq    %rdx, %rcx', '    movq    %r11, %rdx', '    movq    %r10, %rsi', '    call    sbn3i_mul_1',
          '    movq    (%rsp), %rdi', '    movq    16(%rsp), %rdx',
          '    movq    %rdx, %rcx', '    shlq    $1, %rcx', '    shrq    $1, %rcx', '    movq    %rax, -8(%rdi,%rcx,8)',
          '    testq   %rax, %rax', '    movq    8(%rsp), %rax', '    leaq    24(%rsp), %rsp', '    jz      .Lstrip_n', '    ret',
          '.Lafter:                                    # frame: z, e_top, ns',
          '    movq    (%rsp), %rdi', '    movq    8(%rsp), %rax', '    movq    16(%rsp), %rdx', '    addq    $24, %rsp',
          '.Ltop:                                      # rdi z, rax e, rdx ns: strip a zero top limb',
          '    movq    %rdx, %rcx', '    shlq    $1, %rcx', '    shrq    $1, %rcx',
          '    cmpq    $0, -8(%rdi,%rcx,8)', '    je      .Lstrip_n', '    ret',
          '.Lstrip:                                    # rax e, rdx ns, top limb zero',
          '    movq    %rdx, %rcx', '    shlq    $1, %rcx', '    shrq    $1, %rcx',
          '.Lstrip_n:',
          '    decq    %rax', '    decq    %rdx', '    decq    %rcx', '    jz      .Lzero',
          '    cmpq    $0, -8(%rdi,%rcx,8)', '    je      .Lstrip_n', '    ret',
          '.Lzero:', '    xorl    %eax, %eax', '    xorl    %edx, %edx', '    ret',
          '    .size SYM(mul), .-SYM(mul)', '',
          '    .p2align 5', '    .globl SYM(sqr)', '    .type SYM(sqr), @function', 'SYM(sqr):',
          '    movq    16(%rsi), %r10', '    movq    8(%rsi), %rax', '    addq    %rax, %rax',   # e_top = 2 ea
          '    subq    $2, %rdx', '    sarq    $6, %rdx',
          '    movq    %rax, %r9', '    subq    %rdx, %r9', '    jle     .Lzero',
          '    addq    %r10, %r10', '    leaq    (%r9,%r9), %rdx',
          '    subq    %rdx, %r10', '    jb      .Ls_full',
          '    movq    (%rsi), %rsi', '    leaq    (%rsi,%r10,4), %rsi',
          '    movq    %rax, S_ETOP', '    movq    %r9, S_NS',
          '    leaq    .Ls_tab(%rip), %rdx', '    jmp     *-8(%rdx,%r9,8)']
    for k in range(1, KQ + 1):
        block(L, f'.Ls_{k}', sqr_body(k))
    L += ['.Ls_u52:',
          '    movq    %rsi, %rdx', '    jmp     .Lu52',
          '.Ls_full:                                   # the whole operand: 2 na limbs, exact',
          '    addq    %rdx, %r10', '    shrq    $1, %r10', '    movq    (%rsi), %rsi',
          '    cmpq    $1, %r10', '    jne     3f',
          '    movq    (%rsi), %rdx', '    movq    %rsi, %r10', '    movl    $1, %r11d', '    movl    $2, %r8d',
          '    jmp     .Lm_x1',
          '3:  subq    $24, %rsp', '    movq    %rdi, (%rsp)', '    movq    %rax, 8(%rsp)',
          '    leaq    (%r10,%r10), %rax', '    movq    %rax, 16(%rsp)',
          '    movq    %r10, %rdx', '    movq    %rsi, %rcx', '    movq    %r10, %r8', '    call    sbn3f_full',
          '    jmp     .Lafter',
          '    .size SYM(sqr), .-SYM(sqr)', '',
          '    .section .data.rel.ro.local, "aw"', '    .p2align 3', '.Lm_tab:']
    L += [f'    .quad   .Lm_{k}' if k <= KM else '    .quad   .Lm_u52' for k in range(1, KTAB + 1)]
    L += ['.Ls_tab:']
    L += [f'    .quad   .Ls_{k}' if k <= KQ else '    .quad   .Ls_u52' for k in range(1, KTAB + 1)]
    L += ['', '    .section .note.GNU-stack,"",@progbits']
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--out', help='write here instead (variants)')
    args = ap.parse_args()
    t = text()
    if args.check:
        if not OUT.exists() or OUT.read_text() != t:
            raise SystemExit(f'{OUT.relative_to(ROOT)} is stale')
        print(f'OK: fp mul / sqr, register columns to {KRM} / {KRQ}, rows to {KM} / {KQ}')
    else:
        Path(args.out or OUT).write_text(t)


if __name__ == '__main__':
    main()
