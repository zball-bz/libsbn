#!/usr/bin/env python3
"""Generate the fixed-row MULX/ADX scalar basecases.

src/core/x86_64/mul_basecase_le16.S: sbn3i_mul_basecase_le16(rp, ap, an, bp, bn) for
1 <= an,bn <= 16, the structure of mul_basecase_le6.S at N = 16: an >= bn after a swap, ap
and rp biased by -(16-an) limbs so every row uses the same displacements, the row entry
chosen once by an through a PC-relative table (store-only first row, then addmul rows with
ADCX for the product-high chain and ADOX for the old rp limbs), the row's high limb pending
in r13 for the next row, only r12/r13 saved. Successive blocks alternate the product-high
register (r9/r10) instead of copying it.

src/core/x86_64/sqr_basecase_fixed.S: sbn3i_sqr_basecase_<n>(rp, ap) for n in SQR, straight
line: the cross triangle sum_{i<j} a_i a_j by unrolled rows (row i = a_i * a[i+1..n-1] at
positions 2i+1.., its top limb the previous row's pending high), then one pass
rp = 2*cross + diag(a_i^2) with ADCX doubling each limb with its carry (t + t + CF) and
ADOX adding the square limbs. Cross terms are summed before the doubling; no operand is
doubled. No callee-saved register is touched. 2..6 are reached only through explicit square
entries (sqr_basecase_assumed, SQR bindings); plain 1..6 products take no pointer test.
"""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
LE = ROOT / 'src/core/x86_64/mul_basecase_le16.S'
SQ = ROOT / 'src/core/x86_64/sqr_basecase_fixed.S'
N, SQR = 16, tuple(range(2, 15))


def le(N, sym):
    H = lambda k: '%r9' if k & 1 else '%r10'      # high limb produced by block/entry k
    o = lambda k: 8 * (N - k)                       # displacement of block/entry k
    out = [f'/* Generated by tools/generate_mul_basecase.py; do not edit. {sym}(rp, ap, an, bp, bn):',
           f' * 1 <= an,bn <= {N}, rp has an+bn writable limbs disjoint from ap and bp.',
           f' * The structure of mul_basecase_le6.S at N = {N}; see the generator. */',
           '    .text', '    .p2align 5', f'    .globl {sym}', f'    .type {sym}, @function', f'{sym}:',
           '    pushq   %r12', '    pushq   %r13',
           '    cmpq    %r8, %rdx', '    jae     1f', '    xchgq   %rsi, %rcx', '    xchgq   %rdx, %r8', '1:',
           f'    leaq    -{8 * N}(%rsi,%rdx,8), %rsi', f'    leaq    -{8 * N}(%rdi,%rdx,8), %rdi',
           '    leaq    .Ladd_tab(%rip), %r10', '    movslq  (%r10,%rdx,4), %r12', '    addq    %r10, %r12',
           '    leaq    .Lmul_tab(%rip), %r10', '    movslq  (%r10,%rdx,4), %rax', '    addq    %r10, %rax',
           '    movq    (%rcx), %rdx', '    xorl    %r11d, %r11d', '    jmp     *%rax']
    e = out.append
    for n in range(N, 0, -1):                       # store-only first row
        e(f'.Lmul_e{n}:')
        e(f'    mulxq   {o(n)}(%rsi), %rax, {H(n)}')
        e(f'    movq    %rax, {o(n)}(%rdi)')
        e(f'    jmp     .Lmul_b{n - 1}')
    for k in range(N - 1, 0, -1):
        e(f'.Lmul_b{k}:')
        e(f'    mulxq   {o(k)}(%rsi), %rax, {H(k)}')
        e(f'    adcxq   {H(k + 1)}, %rax')
        e(f'    movq    %rax, {o(k)}(%rdi)')
    out += ['.Lmul_b0:', f'    adcxq   %r11, {H(1)}', f'    movq    {H(1)}, %r13',
            '    decq    %r8', '    jz      .Lstore_pending_done', '    leaq    8(%rcx), %rcx', '    leaq    8(%rdi), %rdi',
            '.Louter:', '    movq    (%rcx), %rdx', '    xorl    %r11d, %r11d', '    jmp     *%r12']
    for n in range(N, 0, -1):                       # addmul rows; the top limb takes r13
        e(f'.Ladd_e{n}:')
        e(f'    mulxq   {o(n)}(%rsi), %rax, {H(n)}')
        e(f'    adoxq   {o(n)}(%rdi), %rax' if n > 1 else '    adoxq   %r13, %rax')
        e(f'    movq    %rax, {o(n)}(%rdi)')
        e(f'    jmp     .Ladd_b{n - 1}')
    for k in range(N - 1, 0, -1):
        e(f'.Ladd_b{k}:')
        e(f'    mulxq   {o(k)}(%rsi), %rax, {H(k)}')
        e(f'    adcxq   {H(k + 1)}, %rax')
        e(f'    adoxq   {o(k)}(%rdi), %rax' if k > 1 else '    adoxq   %r13, %rax')
        e(f'    movq    %rax, {o(k)}(%rdi)')
    out += ['.Ladd_b0:', f'    adoxq   %r11, {H(1)}', f'    adcxq   %r11, {H(1)}', f'    movq    {H(1)}, %r13',
            '    decq    %r8', '    jz      .Lstore_pending_done', '    leaq    8(%rcx), %rcx', '    leaq    8(%rdi), %rdi',
            '    jmp     .Louter', '.Lstore_pending_done:', f'    movq    %r13, {8 * N}(%rdi)',
            '.Ldone:', '    popq    %r13', '    popq    %r12', '    ret']
    for t in ('mul', 'add'):
        out += ['    .p2align 2', f'.L{t}_tab:', f'    .long   .Ldone - .L{t}_tab']
        out += [f'    .long   .L{t}_e{n} - .L{t}_tab' for n in range(1, N + 1)]
    out += [f'    .size {sym}, .-{sym}', '    .section .note.GNU-stack,"",@progbits']
    return '\n'.join(out) + '\n'


def sqr(ns, prefix):
    out = ['/* Generated by tools/generate_mul_basecase.py; do not edit. ' +
           ', '.join(f'{prefix}{n}' for n in ns) + '(rp, ap):',
           ' * the square of n limbs into 2n limbs, rp disjoint from ap; see the generator. */', '    .text']
    e = out.append
    H = ('%r9', '%r10')
    for n in ns:
        sym = f'{prefix}{n}'
        out += ['    .p2align 5', f'    .globl {sym}', f'    .type {sym}, @function', f'{sym}:']
        for i in range(n - 1):                      # cross row i: positions 2i+1 .. i+n-1
            e(f'    movq    {8 * i}(%rsi), %rdx')
            e('    xorl    %r11d, %r11d')
            js = list(range(i + 1, n))
            for t, j in enumerate(js):
                p = i + j
                e(f'    mulxq   {8 * j}(%rsi), %rax, {H[t & 1]}')
                if t: e(f'    adcxq   {H[(t - 1) & 1]}, %rax')
                if i: e('    adoxq   %r8, %rax' if t == len(js) - 1 else f'    adoxq   {8 * p}(%rdi), %rax')
                e(f'    movq    %rax, {8 * p}(%rdi)')
            h = H[(len(js) - 1) & 1]
            if i: e(f'    adoxq   %r11, {h}')
            e(f'    adcxq   %r11, {h}')
            e(f'    movq    {h}, %r8')
        e(f'    movq    %r8, {8 * (2 * n - 2)}(%rdi)')
        e('    xorl    %r11d, %r11d')               # rp = 2*cross + diag
        for i in range(n):
            e(f'    movq    {8 * i}(%rsi), %rdx')
            e('    mulxq   %rdx, %rax, %rcx')
            for k, s in ((2 * i, '%rax'), (2 * i + 1, '%rcx')):
                if k == 0: e('    xorl    %r9d, %r9d')
                elif k == 2 * n - 1: e('    movl    $0, %r9d')          # keeps CF/OF
                else: e(f'    movq    {8 * k}(%rdi), %r9')
                e('    adcxq   %r9, %r9')
                e(f'    adoxq   {s}, %r9')
                e(f'    movq    %r9, {8 * k}(%rdi)')
        out += ['    ret', f'    .size {sym}, .-{sym}']
    out += ['    .section .note.GNU-stack,"",@progbits']
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    files = {LE: le(N, 'sbn3i_mul_basecase_le16'), SQ: sqr(SQR, 'sbn3i_sqr_basecase_')}
    if args.check:
        for path, text in files.items():
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path.relative_to(ROOT)} is stale')
        print(f'OK: scalar basecases le{N} and squares {SQR[0]}..{SQR[-1]}')
    else:
        for path, text in files.items():
            path.write_text(text)


if __name__ == '__main__':
    main()
