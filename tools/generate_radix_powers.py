#!/usr/bin/env python3
"""Generate the immutable all-base power prefix using exact integer arithmetic."""
import argparse
from pathlib import Path
from generate_radix_bounds import floor_log
ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'src/radix/power_bank.cpp'
INVERSE_WORDS=264
INVERSE_FRAGMENTS=176
def content():
    words=[];entries=[]
    for odd in range(3,64,2):
        value=odd**64
        for level in range(9):
            start=len(words);n=(value.bit_length()+63)//64
            words.extend((value>>(64*j))&((1<<64)-1) for j in range(n))
            words.extend([0]*(((n+15)//8)*8-n))
            entries.append((start,len(words)-start))
            value*=value
    lines=['// Generated by tools/generate_radix_powers.py; exact integers, no runtime initialization.',
           '#include "radix/power_bank.hpp"','#include "common/checked.hpp"','namespace sbn::v3::radix {','static_assert(fixed_power_levels==9);','namespace {',
           'struct Entry { uint32_t offset,capacity; };',
           f'alignas(64) constexpr uint64_t words[{len(words)}] = {{']
    lines+=['    '+','.join(f'0x{x:016x}ULL' for x in words[j:j+4])+',' for j in range(0,len(words),4)]
    lines+=['};',f'constexpr Entry entries[{len(entries)}] = {{']
    lines+=['    {'+str(a)+','+str(b)+'},' for a,b in entries]
    lines+=['};','constexpr ParseLeafPlan leaf_plans[65] = {']
    logs=[floor_log(b) for b in range(65)]
    def capacity(b,d):return (((logs[b]+1)*d>>56)+2+63)//64
    for b in range(65):
        if b<3 or b&(b-1)==0:lines+=['    {},'];continue
        twos=(b&-b).bit_length()-1;odd=b>>twos
        ns=[0]+[capacity(b,64*j) for j in range(1,9)]
        pn=[capacity(odd,64<<j) for j in range(3)]
        ptr=['words+'+str(entries[((odd-3)//2)*9+j][0]) for j in range(3)]
        lines+=['    {'+str(twos)+',{'+','.join(map(str,ns))+'},{'+','.join(map(str,pn))+'},{'+','.join(ptr)+'}},']
    lines+=['};']
    precisions={}
    for b in range(3,64):
        if b&(b-1)==0:continue
        odd=b//(b&-b)
        for f in range(1,INVERSE_FRAGMENTS+1):
            n=(((logs[b]+1)*(64*f+8)>>56)+2+16+63)//64
            if n<=INVERSE_WORDS:precisions[odd,f]=max(n,precisions.get((odd,f),0))
    inverses=[];directory=[]
    for odd in range(3,64,2):
        for f in range(1,INVERSE_FRAGMENTS+1):
            n=precisions.get((odd,f),0)
            if not n:directory.append((0,0,0));continue
            value=odd**(64*f);bits=value.bit_length()
            inv=((1<<(128*n))-1)//(value<<(64*n-bits))
            offset=len(inverses);inverses.extend((inv>>(64*j))&((1<<64)-1) for j in range(n+1))
            directory.append((offset,n,bits))
    lines += [f'alignas(64) constexpr uint64_t inverse_words[{len(inverses)}] = {{']
    lines += ['    '+','.join(f'0x{x:016x}ULL' for x in inverses[j:j+4])+',' for j in range(0,len(inverses),4)]
    lines += ['};','struct InverseEntry {uint32_t offset;uint16_t words,bits;};',
              f'constexpr InverseEntry inverse_entries[31*{INVERSE_FRAGMENTS}] = {{']
    lines += ['    {'+','.join(map(str,e))+'},' for e in directory]
    lines+=['};','}',
            'FixedPower fixed_power(unsigned odd,unsigned level) noexcept {',
            '    if(odd<3 || odd>63 || !(odd&1) || level>=fixed_power_levels)return {};',
            '    const auto &e=entries[((odd-3)/2)*fixed_power_levels+level];',
            '    return {words+e.offset,e.capacity};','}',
            'const ParseLeafPlan &parse_leaf_plan(unsigned base) noexcept {',
            '    require(base>=3&&base<=63&&(base&(base-1)),SBN3_FATAL_ARGUMENT,"parse leaf base");',
            '    return leaf_plans[base];','}',
            'FixedIntegerInverse fixed_integer_inverse(unsigned base,unsigned fragments,size_t n) noexcept {',
            f'    static_assert(fixed_integer_inverse_words=={INVERSE_WORDS}&&fixed_integer_inverse_fragments=={INVERSE_FRAGMENTS});',
            '    if(base<3||base>63||!(base&(base-1))||!fragments||fragments>fixed_integer_inverse_fragments||n>fixed_integer_inverse_words)return {};',
            '    const unsigned twos=unsigned(__builtin_ctz(base)),odd=base>>twos;',
            '    const auto &e=inverse_entries[((odd-3)/2)*fixed_integer_inverse_fragments+fragments-1];',
            '    const int64_t shift=int64_t(64*n)-e.bits-int64_t(twos)*64*fragments-2;',
            '    if(n>e.words||shift<0)return {};',
            '    return {inverse_words+e.offset+e.words-n,unsigned(shift)};','}',
            'size_t fixed_power_bytes() noexcept { return sizeof(words)+sizeof(entries)+sizeof(leaf_plans)+sizeof(inverse_words)+sizeof(inverse_entries); }','}']
    return '\n'.join(lines)+'\n'
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args();text=content()
    if a.check:
        if not DEST.exists() or DEST.read_text()!=text:raise SystemExit('radix power constants are stale')
        print('OK: immutable power prefix for all 31 odd bases')
    else:DEST.write_text(text)
if __name__=='__main__':main()
